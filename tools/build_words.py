"""Builds frontend/words.js from tools/answers.txt and the macOS system dictionary.

Usage:  python3 tools/build_words.py

- ANSWERS: common, friendly 5-letter words picked as the secret word.
- VALID:   everything a player is allowed to guess (answers + dictionary words
           + simple plurals of 4-letter words), so players aren't rejected for
           ordinary words like "boats".
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
DICT = Path("/usr/share/dict/words")

five = re.compile(r"^[a-z]{5}$")
four = re.compile(r"^[a-z]{4}$")

raw_answers = [w.strip().lower() for w in (ROOT / "tools/answers.txt").read_text().split()]
answers = sorted({w for w in raw_answers if five.match(w)})
skipped = sorted({w for w in raw_answers if not five.match(w)})
if skipped:
    print("Skipped (not 5 letters):", ", ".join(skipped))

valid = set(answers)
if DICT.exists():
    for line in DICT.read_text(errors="ignore").splitlines():
        w = line.strip()
        if five.match(w):
            valid.add(w)
        elif four.match(w) and not w.endswith("s"):
            valid.add(w + "s")
else:
    print("No system dictionary found; only answer words will be accepted.")

out = ROOT / "frontend/words.js"
out.write_text(
    "// Generated by tools/build_words.py - do not edit by hand.\n"
    f"const ANSWERS = {json.dumps([w.upper() for w in answers])};\n"
    f"const VALID_WORDS = new Set({json.dumps(sorted(w.upper() for w in valid), separators=(',', ':'))});\n"
)
print(f"Wrote {out.relative_to(ROOT)}: {len(answers)} answers, {len(valid)} valid guesses")

# ---- Rasa training data -------------------------------------------------
# Words that are also voice commands stay out of the lookup table, so "clear"
# means "clear the row" (players can still say "guess clear").
COMMAND_WORDS = {"enter", "clear", "hello", "howdy", "thank", "quiet", "right",
                 "sorry", "check", "again", "pause", "hurry", "shush", "start"}

lookup = ROOT / "rasa/data/lookup_words.yml"
lookup.write_text(
    "# Generated by tools/build_words.py - do not edit by hand.\n"
    'version: "3.1"\nnlu:\n  - lookup: word\n    examples: |\n'
    + "".join(f"      - {w}\n" for w in sorted(valid - COMMAND_WORDS))
)

# Bare-word and phrased guesses so the model learns "a lone word = a guess".
import random
rng = random.Random(7)
pool = sorted(set(answers) - COMMAND_WORDS)
bare = rng.sample(pool, min(120, len(pool)))
templates = ["guess {}", "try {}", "my guess is {}", "my guess would be {}", "I'll go with {}",
             "is it {}", "how about {}", "the word is {}", "I think it's {}", "let's try {}",
             "maybe {}", "could it be {}", "I want to guess {}", "what about {}"]
phrased = [rng.choice(templates).format(f"[{w}](word)") for w in rng.sample(pool, min(80, len(pool)))]
gen = ROOT / "rasa/data/nlu_guesses.yml"
gen.write_text(
    "# Generated by tools/build_words.py - do not edit by hand.\n"
    'version: "3.1"\nnlu:\n  - intent: make_guess\n    examples: |\n'
    + "".join(f"      - [{w}](word)\n" for w in bare)
    + "".join(f"      - {p}\n" for p in phrased)
)
print(f"Wrote {lookup.relative_to(ROOT)} and {gen.relative_to(ROOT)}")
